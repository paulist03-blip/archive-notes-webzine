  function row(href, image, imageAlt, title, description, type, thumbClass) {
    return {
      href: href,
      image: image,
      imageAlt: imageAlt,
      title: title,
      description: description,
      type: type,
      thumbClass: thumbClass || "cover-thumb"
    };
  }

  function text(selector, value) {
    var element = document.querySelector(selector);
    if (element) {
      element.textContent = value;
    }
  }

  function pills(selector, values) {
    var element = document.querySelector(selector);
    if (!element) {
      return;
    }
    element.replaceChildren();
    values.forEach(function (value) {
      var pill = document.createElement("span");
      pill.className = "pill";
      pill.textContent = value;
      element.appendChild(pill);
    });
  }

  function createRow(item) {
    var link = document.createElement("a");
    link.className = "archive-row";
    link.href = item.href;

    var thumb = document.createElement("div");
    thumb.className = "thumb " + item.thumbClass;

    var image = document.createElement("img");
    image.src = item.image;
    image.alt = item.imageAlt;
    thumb.appendChild(image);

    var copy = document.createElement("div");
    var title = document.createElement("h3");
    title.textContent = item.title;
    var description = document.createElement("p");
    description.textContent = item.description;
    copy.appendChild(title);
    copy.appendChild(description);

    var type = document.createElement("span");
    type.className = "row-type";
    type.textContent = item.type;

    link.appendChild(thumb);
    link.appendChild(copy);
    link.appendChild(type);

    return link;
  }

  function normalizeIssueId(id) {
    if (!id) {
      return "";
    }
    return String(id).replace(/^issue-/, "").padStart(2, "0");
  }

  function renderIssue(id, options) {
    var issueId = normalizeIssueId(id);
    var issue = issues[issueId] || issues[String(Number(issueId))];
    var container = document.querySelector("[data-issue-items]");
    if (!issue || !container) {
      return false;
    }

    document.body.classList.add("is-issue-switching");

    text("[data-issue-eyebrow]", issue.eyebrow);
    text("[data-issue-hero-lede]", issue.lede);
    text("[data-issue-card-label]", "Issue " + issue.id);
    text("[data-issue-card-byline]", issue.byline);
    text("[data-issue-notes-title]", issue.title);
    text("[data-issue-notes-copy]", issue.notes);

    var stamp = document.querySelector("[data-issue-stamp]");
    if (stamp) {
      stamp.innerHTML = "Issue<br />" + issue.id;
    }

    var heroMedia = document.querySelector("[data-issue-hero-media]");
    if (heroMedia) {
      heroMedia.setAttribute("aria-label", "Issue " + issue.id + " 대표 글");
    }

    var heroImage = document.querySelector("[data-issue-hero-image]");
    if (heroImage) {
      heroImage.src = issue.image;
      heroImage.alt = issue.imageAlt;
    }

    var cardLink = document.querySelector("[data-issue-card-link]");
    if (cardLink) {
      cardLink.href = issue.href;
      cardLink.textContent = issue.title;
    }

    pills("[data-issue-tags]", issue.tags);
    pills("[data-issue-info]", issue.info);

    var drawer = container.querySelector(".essay-drawer");
    Array.prototype.slice.call(container.querySelectorAll(":scope > .archive-row")).forEach(function (element) {
      element.remove();
    });

    var fragment = document.createDocumentFragment();
    issue.rows.forEach(function (item) {
      fragment.appendChild(createRow(item));
    });
    container.insertBefore(fragment, drawer || null);
    container.setAttribute("aria-label", "Issue " + issue.id + " 대표 글 목록");

    Array.prototype.slice.call(document.querySelectorAll("[data-issue-select]")).forEach(function (link) {
      var selected = normalizeIssueId(link.dataset.issueSelect) === normalizeIssueId(issue.id);
      link.classList.toggle("is-selected", selected);
      if (selected) {
        link.setAttribute("aria-current", "true");
      } else {
        link.removeAttribute("aria-current");
      }
    });

    var summarySmall = document.querySelector(".essay-drawer summary small");
    if (summarySmall) {
      summarySmall.textContent = "현재 Issue " + issue.id;
    }

    if (options && options.push) {
      history.replaceState(null, "", "#issue-" + issue.id);
    }

    if (options && options.scroll) {
      var target = document.querySelector("#notes") || document.querySelector(".hero");
      if (target) {
        target.scrollIntoView({
          behavior: window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth",
          block: "start"
        });
      }
    }

    window.setTimeout(function () {
      document.body.classList.remove("is-issue-switching");
    }, 180);

    return true;
  }

  function issueFromHash() {
    var match = window.location.hash.match(/^#issue-(\d{1,2})$/);
    return match ? match[1] : "";
  }

  document.addEventListener("DOMContentLoaded", function () {
    Array.prototype.slice.call(document.querySelectorAll("[data-issue-select]")).forEach(function (link) {
      link.addEventListener("click", function (event) {
        var issueId = link.dataset.issueSelect;
        if (!issues[normalizeIssueId(issueId)] && !issues[String(Number(normalizeIssueId(issueId)))]) {
          return;
        }
        event.preventDefault();
        renderIssue(issueId, { push: true, scroll: true });
      });
    });

    var hashIssue = issueFromHash();
    if (hashIssue) {
      renderIssue(hashIssue, { push: false, scroll: false });
    } else {
      renderIssue("17", { push: false, scroll: false });
    }

    window.addEventListener("hashchange", function () {
      var nextIssue = issueFromHash();
      if (nextIssue) {
        renderIssue(nextIssue, { push: false, scroll: false });
      }
    });
  });
